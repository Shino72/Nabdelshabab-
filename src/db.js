// جداول بلا عمود id (لا تُضاف لها RETURNING id عند الإدراج)
const NO_ID = new Set(['sessions', 'article_tags', 'article_views_daily', 'site_views_daily', 'ad_stats_daily', 'settings', 'rate_limits', 'nabd_schema']);

// تحويل علامات ? إلى $1 و$2 ... (مع تجاهل ما داخل النصوص الحرفية)
const cache = new Map();
function translate(sql) {
  let out = cache.get(sql);
  if (out) return out;
  let n = 0, inStr = false;
  out = '';
  for (const ch of sql) {
    if (ch === "'") inStr = !inStr;
    out += ch === '?' && !inStr ? `$${++n}` : ch;
  }
  const ins = /^\s*INSERT\s+INTO\s+(\w+)/i.exec(out);
  if (ins && !NO_ID.has(ins[1].toLowerCase()) && !/\bRETURNING\b/i.test(out)) out += ' RETURNING id';
  cache.set(sql, out);
  return out;
}
const norm = (p) => p.map((v) => (v === undefined ? null : v === true ? 1 : v === false ? 0 : v));
const query = (sql, p) => bridge.call('query', { sql: translate(sql), params: norm(p) });
const all = (sql, ...p) => query(sql, p).rows;
const get = (sql, ...p) => query(sql, p).rows[0];
function run(sql, ...p) {
  const r = query(sql, p);
  return { changes: r.count || 0, id: r.rows[0]?.id };
}
const exec = (sql) => { bridge.call('query', { sql, params: [] }); };

let depth = 0;
function tx(fn) {
  if (depth > 0) return fn();
  depth++;
  bridge.call('begin');
  try {
    const r = fn();
    if (r && typeof r.then === 'function') throw new Error('tx() لا يقبل دوال غير متزامنة');
    bridge.call('commit');
    return r;
  } catch (e) {
    try { bridge.call('rollback'); } catch { /* تجاهل */ }
    throw e;
  } finally { depth--; }
}

// قاعدة بيانات Supabase مشتركة؟ نرفض العمل فوق جداول تطبيق آخر بدل الكتابة فيها
const FOREIGN_MARKERS = ['staff_profiles', 'article_revisions'];

// يجب انتظارها قبل أول استعلام في كل طلب (انظر bridge.start)
async function connect() {
  if (!config.db) return; // open() يشرح الخطأ
  bridge.configure(config.db);
  await bridge.start();
}

function open() {
  if (!config.db) {
    // أسماء المتغيرات الموجودة فقط (بدون قيمها) لتسهيل معرفة ما ينقص
    const names = Object.keys(process.env).filter((k) => /POSTGRES|SUPABASE|DATABASE/.test(k)).sort();
    const found = names.length ? ` المتغيرات الموجودة: ${names.join('، ')}` : ' لا يوجد أي متغير لقاعدة البيانات في هذه النسخة.';
    throw Object.assign(new Error(`لم يُضبط رابط قاعدة البيانات. أضف DATABASE_URL (أو اربط Supabase بالمشروع على Vercel ثم أعد النشر).${found}`), { code: 'NO_DATABASE' });
  }
  bridge.configure(config.db);
  return tx(() => {
    // لا ننتظر للأبد إن كانت نسخة أخرى عالقة وهي تمسك القفل
    exec("SET LOCAL lock_timeout = '10s'");
    all('SELECT pg_advisory_xact_lock(724519033)');
    exec('CREATE TABLE IF NOT EXISTS nabd_schema (version integer NOT NULL)');
    const row = get('SELECT version FROM nabd_schema LIMIT 1');
    const version = row ? row.version : 0;
    if (!row) run('INSERT INTO nabd_schema (version) VALUES (0)');
    if (version === 0) {
      for (const t of FOREIGN_MARKERS) {
        if (get('SELECT to_regclass(?) AS t', t).t) throw Object.assign(new Error('قاعدة البيانات هذه تخص تطبيقًا آخر (مثل موقع لحظة). أنشئ مشروع Supabase منفصلًا لنبض الشباب.'), { code: 'FOREIGN_DATABASE' });
      }
    }
    for (let i = version; i < MIGRATIONS.length; i++) exec(MIGRATIONS[i]);
    if (version < MIGRATIONS.length) {
      run('UPDATE nabd_schema SET version = ?', MIGRATIONS.length);
      lockDown();
    }
    return { fresh: version === 0 };
  });
}

// على Supabase تُتاح جداول المخطط public عبر واجهة REST بمفتاح anon: نغلقها بالكامل.
// الموقع يتصل بدور مالك الجداول، فلا تؤثر هذه القيود عليه.
function lockDown() {
  exec(`DO $$
DECLARE t record;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t.tablename);
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM anon, authenticated', current_schema());
    EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM anon, authenticated', current_schema());
  END IF;
END $$`);
}

function close() { bridge.close(); cache.clear(); }

