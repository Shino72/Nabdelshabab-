async function seedDemo() {
  if (Articles.hasDemo()) return 0;
  const cats = Object.fromEntries(all('SELECT id, slug FROM categories').map((c) => [c.slug, c.id]));
  const authorByCat = {};
  for (const [name, title, role, catList] of WRITERS) {
    const email = `demo-${crypto.randomBytes(4).toString('hex')}@demo.invalid`;
    // كلمة مرور عشوائية غير معروفة: الحسابات التجريبية لا يمكنها تسجيل الدخول
    const id = Users.create({ name, email, passwordHash: await hashPassword(crypto.randomBytes(24).toString('hex')), role, title: `${title} (حساب تجريبي)`, bio: 'حساب تجريبي لعرض صفحة الكاتب.', isDemo: true });
    for (const c of catList) (authorByCat[c] ||= []).push(id);
  }
  const order = [];
  const maxLen = Math.max(...Object.values(DEMO).map((x) => x.length));
  for (let i = 0; i < maxLen; i++) for (const cat of Object.keys(DEMO)) if (DEMO[cat][i]) order.push([cat, i, DEMO[cat][i]]);
  const featured = new Set(['politics:0', 'economy:0', 'tech:0', 'sports:0', 'reports:0']);
  const now = Date.now();
  const ids = [];
  let n = 0;
  tx(() => {
    for (const [cat, i, [title, excerpt, tags, type]] of order) {
      const pool = POOL[cat];
      const parts = [DEMO_NOTE, excerpt, pool[i % 3], `## ${SUBHEADS[cat]}`, pool[(i + 1) % 3]];
      if (n % 3 === 0) parts.push('- النقطة الأولى: توضيح تجريبي لشكل القوائم داخل الخبر.\n- النقطة الثانية: يمكن للمحرر إضافة قوائم وعناوين فرعية واقتباسات.');
      parts.push(pool[(i + 2) % 3]);
      const minutesAgo = n === 0 ? 14 : n * 170 + ((n * 37) % 90);
      const published = new Date(now - minutesAgo * 60000).toISOString();
      const artType = type || (cat === 'opinion' ? 'opinion' : cat === 'reports' ? 'report' : 'news');
      const authors = authorByCat[cat] || authorByCat.politics;
      const id = Articles.save({
        title, excerpt, body: parts.join('\n\n'), cover_image: `/demo-img/${cat}-${i + 1}.svg`, cover_caption: 'صورة توضيحية مولّدة للمحتوى التجريبي',
        category_id: cats[cat], author_id: authors[i % authors.length], type: artType, status: 'published', is_featured: featured.has(`${cat}:${i}`),
        allow_comments: true, tags, published_at: published, created_at: published, updated_at: published, is_demo: true,
        sources: i % 2 === 0 && artType === 'news' ? [{ name: 'مصدر تجريبي للتوضيح', url: 'https://example.com/' }] : [],
        gallery: artType === 'gallery' ? [1, 2, 3, 4, 5, 6].map((k) => ({ image: `/demo-img/${k % 2 ? 'culture' : 'society'}-g${i}${k}.svg`, caption: `صورة توضيحية رقم ${k}` })) : [],
      }, null);
      ids.push(id);
      n++;
    }
    // مشاهدات تجريبية لتعبئة قائمة "الأكثر قراءة" (تُحذف مع حذف المحتوى التجريبي)
    const today = localDay();
    ids.forEach((id, k) => {
      let total = 0;
      for (let d = 0; d < 7; d++) {
        const v = ((id * 7919 + d * 104729) % 400) + (k < 8 ? 300 : 20);
        total += v;
        run('INSERT INTO article_views_daily (article_id, day, views) VALUES (?, ?, ?)', id, addDays(today, -d), v);
      }
      run('UPDATE articles SET views = ? WHERE id = ?', total, id);
    });
  });
  const top = all('SELECT id, title FROM articles WHERE is_demo = 1 ORDER BY published_at DESC LIMIT 3');
  for (const a of top) Breaking.create(`تجريبي: ${a.title}`, a.id, null, null, true);
  return ids.length;
}

function deleteDemo() {
  return tx(() => {
    const n = run('DELETE FROM articles WHERE is_demo = 1').changes;
    run('DELETE FROM breaking_news WHERE is_demo = 1');
    const demoUsers = all('SELECT id FROM users WHERE is_demo = 1');
    for (const u of demoUsers) {
      if (!get('SELECT 1 AS x FROM articles WHERE author_id = ? OR created_by = ?', u.id, u.id)) run('DELETE FROM users WHERE id = ?', u.id);
    }
    run('DELETE FROM tags WHERE id NOT IN (SELECT tag_id FROM article_tags)');
    return n;
  });
}
