// ذاكرة مؤقتة قصيرة: قد يعمل الموقع على عدة نسخ، فتصل تعديلات الإعدادات إلى كل النسخ خلال ثوانٍ
const TTL_MS = 10000;
let cache = null, cachedAt = 0;
function getAll() {
  if (!cache || Date.now() - cachedAt > TTL_MS) {
    const next = { ...DEFAULTS };
    for (const r of all('SELECT key, value FROM settings')) if (r.key in DEFAULTS) next[r.key] = r.value ?? '';
    cache = next;
    cachedAt = Date.now();
  }
  return cache;
}
function setMany(obj) {
  tx(() => {
    for (const [k, v] of Object.entries(obj)) {
      if (!(k in DEFAULTS)) continue;
      run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value', k, String(v ?? ''));
    }
  });
  cache = null;
}
function credits(s = getAll()) {
  return String(s.masthead_credits || '').split('\n').map((l) => l.trim()).filter(Boolean).map((l) => {
    const i = l.indexOf(':');
    return i > 0 ? { label: l.slice(0, i).trim(), name: l.slice(i + 1).trim() } : { label: '', name: l };
  });
}
const pageText = (s, key) => String(s[key] || '').replaceAll('{{site}}', s.site_name);
const invalidate = () => { cache = null; };

module.exports = { DEFAULTS, getAll, setMany, credits, pageText, invalidate };
